"""GPU side of the pedestrian system: three skinned variants, one instance buffer.

The renderer owns an instance of this class (``renderer.peds``).  Per frame it calls
``prepare`` with the crowd's instance rows (it culls, orders by variant and LOD, picks
shadow casters and uploads), then ``draw`` inside the opaque scene pass and
``draw_shadow`` inside the dynamic (vehicle) shadow pass, so people cast and receive
the same shadows the cars do.

The supplied citizen meshes (human_assets.mesh_slots picks one per pedestrian from the instance
seed) and the player share one 15-joint gameplay skeleton.  A citizen is a single 1.4-2.6k
triangle mesh, so both LODs reuse one VAO; the player keeps a detailed and a distance mesh.
Rows are packed by (LOD, mesh slot), each run being one small instanced draw with the right VAO.
Without the citizen asset the old male/female templates are slots 0 and 1.

Material microdetail (pores, leather grain, twill, knit, hair) is a mipmapped texture
array generated by the bake, not analytic noise. Near heads add the supplied
textured 3D eyes and procedural blink lids. Reference heads/eyes stay detailed
at both LODs; distant/shadow garments and bodies use the reduced assembly.
"""
from __future__ import annotations

import ctypes
import math

import numpy as np

from .human_assets import (VERTEX_ATTRIBUTES, STRIDE as HUMAN_STRIDE, slot_template, slot_count, mesh_slots,
                           material_detail, eye_textures, runtime_face_textures, citizen_textures)
from ..render.lod import sphere_mask
from ..shaders import mrt_fs
from ..shaders.pedestrian import PED_VS, PED_FS, PED_SHADOW_VS, PED_SHADOW_FS
from .walker import PED_STRIDE, C_VARIANT, C_SEED

_INSTANCE_FIRST = 8


class PedestrianRenderer:
    MAX_INSTANCES = 400
    DRAW_DISTANCE = 190.
    NEAR_DISTANCE = 34.
    BODY_RADIUS = 1.3                   # umbrella-wide bounding sphere, centred at the waist
    CITIZEN_UNIT = 12       # shared index with the water ripples: bound and restored around the draw
    DETAIL_UNIT = 13
    EYE_UNIT = 14
    FACE_UNIT = 15

    def __init__(self, renderer):
        self.r = renderer
        gl = renderer.gl
        self.count = 0
        self.n_near = self.n_far = 0
        self.last_shadow_casters = 0
        self.ranges = []

        self.prog = renderer._program(PED_VS, mrt_fs(PED_FS, "N * 0.5 + 0.5, 0.0"))
        self.prog_shadow = renderer._program(PED_SHADOW_VS, PED_SHADOW_FS)

        self.inst = gl.glGenBuffers(1)
        gl.glBindBuffer(gl.GL_ARRAY_BUFFER, self.inst)
        gl.glBufferData(gl.GL_ARRAY_BUFFER, self.MAX_INSTANCES * PED_STRIDE * 4, None, gl.GL_STREAM_DRAW)

        self.slots = slot_count()
        self.meshes = {}                # (lod, slot) -> (vao, index_count)
        self.triangles = {}
        self.vaos, self.buffers = [], []
        shared = {}
        for slot in range(self.slots):
            for lod in (0, 1):
                vertices, indices = slot_template(lod, slot)
                if id(vertices) in shared:          # citizens: one mesh serves both LODs
                    self.meshes[lod, slot], self.triangles[lod, slot] = shared[id(vertices)]
                    continue
                vao = gl.glGenVertexArrays(1)
                gl.glBindVertexArray(vao)
                vbo = gl.glGenBuffers(1)
                gl.glBindBuffer(gl.GL_ARRAY_BUFFER, vbo)
                gl.glBufferData(gl.GL_ARRAY_BUFFER, vertices.nbytes, vertices, gl.GL_STATIC_DRAW)
                for location, size, offset in VERTEX_ATTRIBUTES:
                    gl.glEnableVertexAttribArray(location)
                    gl.glVertexAttribPointer(location, size, gl.GL_FLOAT, gl.GL_FALSE, HUMAN_STRIDE,
                                             ctypes.c_void_p(offset * 4))
                ebo = gl.glGenBuffers(1)
                gl.glBindBuffer(gl.GL_ELEMENT_ARRAY_BUFFER, ebo)
                gl.glBufferData(gl.GL_ELEMENT_ARRAY_BUFFER, indices.nbytes, indices, gl.GL_STATIC_DRAW)
                gl.glBindBuffer(gl.GL_ARRAY_BUFFER, self.inst)
                for k in range(PED_STRIDE // 4):
                    location = _INSTANCE_FIRST + k
                    gl.glEnableVertexAttribArray(location)
                    gl.glVertexAttribDivisor(location, 1)
                gl.glBindVertexArray(0)
                self.meshes[lod, slot] = (vao, int(indices.size))
                self.triangles[lod, slot] = int(indices.size) // 3
                shared[id(vertices)] = (self.meshes[lod, slot], self.triangles[lod, slot])
                self.vaos.append(vao)
                self.buffers.extend((vbo, ebo))
        self.detail_tex = self._make_detail_texture()
        self.eye_tex = self._make_detail_texture(eye_textures(), repeat=False)
        self.face_tex = self._make_detail_texture(runtime_face_textures(), repeat=False)
        citizens = citizen_textures()           # absent asset: a 1x1 stand-in keeps the sampler valid
        self.citizen_tex = self._make_detail_texture(
            citizens if citizens is not None else np.zeros((1, 1, 1, 4), np.uint8), repeat=False)

    # ------------------------------------------------------------------ resources
    def _make_detail_texture(self, data=None, repeat=True):
        gl = self.r.gl
        data = material_detail() if data is None else data
        layers, height, width, _ = data.shape
        tex = gl.glGenTextures(1)
        gl.glBindTexture(gl.GL_TEXTURE_2D_ARRAY, tex)
        gl.glPixelStorei(gl.GL_UNPACK_ALIGNMENT, 1)
        gl.glTexImage3D(gl.GL_TEXTURE_2D_ARRAY, 0, gl.GL_RGBA8, width, height, layers, 0,
                        gl.GL_RGBA, gl.GL_UNSIGNED_BYTE, data)
        gl.glTexParameteri(gl.GL_TEXTURE_2D_ARRAY, gl.GL_TEXTURE_MIN_FILTER, gl.GL_LINEAR_MIPMAP_LINEAR)
        gl.glTexParameteri(gl.GL_TEXTURE_2D_ARRAY, gl.GL_TEXTURE_MAG_FILTER, gl.GL_LINEAR)
        wrap = gl.GL_REPEAT if repeat else gl.GL_CLAMP_TO_EDGE
        gl.glTexParameteri(gl.GL_TEXTURE_2D_ARRAY, gl.GL_TEXTURE_WRAP_S, wrap)
        gl.glTexParameteri(gl.GL_TEXTURE_2D_ARRAY, gl.GL_TEXTURE_WRAP_T, wrap)
        gl.glGenerateMipmap(gl.GL_TEXTURE_2D_ARRAY)
        gl.glBindTexture(gl.GL_TEXTURE_2D_ARRAY, 0)
        return tex

    def release(self):
        if not getattr(self, 'vaos', None):
            return
        gl = self.r.gl
        gl.glDeleteVertexArrays(self.vaos)
        gl.glDeleteBuffers(self.buffers + [self.inst])
        if getattr(self, 'detail_tex', None):
            gl.glDeleteTextures([self.detail_tex])
        if getattr(self, 'eye_tex', None):
            gl.glDeleteTextures([self.eye_tex])
        if getattr(self, 'face_tex', None):
            gl.glDeleteTextures([self.face_tex])
        if getattr(self, 'citizen_tex', None):
            gl.glDeleteTextures([self.citizen_tex])
        self.vaos, self.buffers, self.detail_tex = [], [], 0
        self.eye_tex = 0
        self.face_tex = 0
        self.citizen_tex = 0

    def _instances_at(self, first):
        """Point the instance attributes at instance ``first`` of the shared buffer."""
        gl = self.r.gl
        gl.glBindBuffer(gl.GL_ARRAY_BUFFER, self.inst)
        base = first * PED_STRIDE * 4
        for k in range(PED_STRIDE // 4):
            gl.glVertexAttribPointer(_INSTANCE_FIRST + k, 4, gl.GL_FLOAT, gl.GL_FALSE, PED_STRIDE * 4,
                                     ctypes.c_void_p(base + k * 16))

    def _draw_range(self, lod, slot, first, count):
        if count <= 0:
            return
        gl = self.r.gl
        vao, index_count = self.meshes[lod, slot]
        gl.glBindVertexArray(vao)
        self._instances_at(first)
        gl.glDrawElementsInstanced(gl.GL_TRIANGLES, index_count, gl.GL_UNSIGNED_INT, None, count)
        self.r.last_draw_calls += 1

    # ------------------------------------------------------------------ per frame
    def prepare(self, rows, eye, planes, light):
        """Cull, order and upload. -> shadow-cache key (None when nothing casts into the light box)."""
        self.count = self.n_near = self.n_far = 0
        self.last_shadow_casters = 0
        self.ranges = []
        if rows is None or not len(rows):
            return None
        from ..render.renderer import frustum_planes
        rows = np.asarray(rows, np.float32)
        eye = np.asarray(eye, np.float64)
        centre = rows[:, 0:3].astype(np.float64)
        centre[:, 2] += .9
        dist = np.sqrt(((centre - eye) ** 2).sum(axis=1))
        alive = rows[:, 21] > 0.
        visible = sphere_mask(centre, self.BODY_RADIUS, eye, self.DRAW_DISTANCE, planes) & alive
        casters = np.zeros(len(rows), bool)
        if light is not None:
            casters = sphere_mask(centre, self.BODY_RADIUS, eye, math.inf,
                                  frustum_planes(light.matrix.astype(np.float64))) & alive
            casters &= dist < self.DRAW_DISTANCE * .8
        near = visible & (dist < self.NEAR_DISTANCE)
        far = visible & ~near
        shadow_only = casters & ~visible
        slot = mesh_slots(rows[:, C_VARIANT], rows[:, C_SEED])

        # Pack contiguous (LOD, mesh slot) runs.  The first run is always LOD 0, so the
        # same instance ranges can be reused by the shadow pass with LOD 1.
        parts, lod_tag, variant_tag, visible_tag = [], [], [], []
        for lod, select, vis in ((0, near, True), (1, far, True), (1, shadow_only, False)):
            idx = np.flatnonzero(select)
            if not len(idx):
                continue
            idx = idx[np.argsort(dist[idx])]
            v = slot[idx]
            for var in range(self.slots):
                chosen = idx[v == var]
                if not len(chosen):
                    continue
                parts.append(chosen)
                lod_tag.append(np.full(len(chosen), lod, np.int8))
                variant_tag.append(np.full(len(chosen), var, np.int8))
                visible_tag.append(np.full(len(chosen), vis, bool))
        if not parts:
            return None
        order = np.concatenate(parts)
        lod_tag = np.concatenate(lod_tag)
        variant_tag = np.concatenate(variant_tag)
        visible_tag = np.concatenate(visible_tag)
        if len(order) > self.MAX_INSTANCES:
            order = order[:self.MAX_INSTANCES]
            lod_tag = lod_tag[:self.MAX_INSTANCES]
            variant_tag = variant_tag[:self.MAX_INSTANCES]
            visible_tag = visible_tag[:self.MAX_INSTANCES]

        start = 0
        for i in range(1, len(order) + 1):
            if (i == len(order) or lod_tag[i] != lod_tag[start]
                    or variant_tag[i] != variant_tag[start] or visible_tag[i] != visible_tag[start]):
                self.ranges.append((int(lod_tag[start]), int(variant_tag[start]), start, i - start,
                                    bool(visible_tag[start])))
                start = i

        self.count = len(order)
        self.n_near = int(np.count_nonzero(lod_tag == 0))
        self.n_far = int(np.count_nonzero(lod_tag == 1))
        data = np.ascontiguousarray(rows[order])
        gl = self.r.gl
        gl.glBindBuffer(gl.GL_ARRAY_BUFFER, self.inst)
        gl.glBufferData(gl.GL_ARRAY_BUFFER, data.nbytes, None, gl.GL_STREAM_DRAW)
        gl.glBufferSubData(gl.GL_ARRAY_BUFFER, 0, data.nbytes, data)
        chosen_casters = casters[order]
        if not chosen_casters.any():
            return None
        self.last_shadow_casters = int(chosen_casters.sum())
        pose = np.ascontiguousarray(data[chosen_casters][:, [0, 1, 2, 3, 4, 5, 7, 21, 22]])
        return (light.matrix.tobytes(), pose.tobytes())

    def draw(self, common, light, sky):
        if not self.count:
            return
        r, gl = self.r, self.r.gl
        p = self.prog
        gl.glUseProgram(p)
        common(p)
        r._shadow_uniforms(p, light, sky)
        r._lamp_uniforms(p)
        r._float(p, 'uTime', r._tshader())
        gl.glActiveTexture(gl.GL_TEXTURE0 + self.DETAIL_UNIT)
        gl.glBindTexture(gl.GL_TEXTURE_2D_ARRAY, self.detail_tex)
        gl.glUniform1i(r._loc(p, 'uMaterialDetail'), self.DETAIL_UNIT)
        gl.glActiveTexture(gl.GL_TEXTURE0 + self.EYE_UNIT)
        gl.glBindTexture(gl.GL_TEXTURE_2D_ARRAY, self.eye_tex)
        gl.glUniform1i(r._loc(p, 'uEyeTextures'), self.EYE_UNIT)
        gl.glActiveTexture(gl.GL_TEXTURE0 + self.FACE_UNIT)
        gl.glBindTexture(gl.GL_TEXTURE_2D_ARRAY, self.face_tex)
        gl.glUniform1i(r._loc(p, 'uFaceTextures'), self.FACE_UNIT)
        gl.glActiveTexture(gl.GL_TEXTURE0 + self.CITIZEN_UNIT)
        previous = int(gl.glGetIntegerv(gl.GL_TEXTURE_BINDING_2D_ARRAY))   # the water ripples live here
        gl.glBindTexture(gl.GL_TEXTURE_2D_ARRAY, self.citizen_tex)
        gl.glUniform1i(r._loc(p, 'uCitizenTextures'), self.CITIZEN_UNIT)
        gl.glDisable(gl.GL_CULL_FACE)
        tris = 0
        for lod, slot, first, count, visible in self.ranges:
            if visible:
                self._draw_range(lod, slot, first, count)
                tris += self.triangles[lod, slot] * count
        gl.glBindVertexArray(0)
        gl.glActiveTexture(gl.GL_TEXTURE0 + self.CITIZEN_UNIT)
        gl.glBindTexture(gl.GL_TEXTURE_2D_ARRAY, previous)
        gl.glActiveTexture(gl.GL_TEXTURE0)
        r.last_ped_tris = tris

    def draw_shadow(self, light):
        """Inside the dynamic shadow pass (framebuffer, viewport and depth state already set)."""
        if not self.count:
            return
        r, gl = self.r, self.r.gl
        p = self.prog_shadow
        gl.glUseProgram(p)
        r._mat(p, 'uLightSpaceMatrix', light.matrix)
        r._float(p, 'uTime', r._tshader())
        for lod, slot, first, count, visible in self.ranges:
            self._draw_range(1, slot, first, count)
        gl.glBindVertexArray(0)
