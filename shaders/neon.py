BLOOM_BLUR_FS = """
#version 330 core
in vec2 vUV;
uniform sampler2D uImage;
uniform vec2 uDir;
uniform vec2 uTexel;
out vec4 FragColor;
void main() {
    vec3 sum = texture(uImage, vUV).rgb * 0.227027;
    vec2 o = uDir * uTexel;
    sum += texture(uImage, vUV + o * 1.384615).rgb * 0.316216;
    sum += texture(uImage, vUV - o * 1.384615).rgb * 0.316216;
    sum += texture(uImage, vUV + o * 3.230769).rgb * 0.070270;
    sum += texture(uImage, vUV - o * 3.230769).rgb * 0.070270;
    FragColor = vec4(sum, 1.0);
}
"""
