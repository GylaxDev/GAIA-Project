"""Neon signage, crown LEDs and bloom shaders.

Sign geometry is generated by ``osm3d.urban``; the look lives here.  Each
sign carries a colour, a seed and a style kind:

    style.y == 1.0  vertical blade sign / marquee
    style.y == 2.0+ ground floor shop window (warm parallax interior)
    style.y == 3.0  signage band above the shopfront
    style.y == 4.0  big advertising screen (drop-in texture array or procedural)
    style.y >= 5.0  crown LED rib
    style.y >= 6.0  spire beacon
"""

from ..core.config import NEON_EXPOSURE_STOPS
from .materials import MATERIAL_LIGHT

# Mean brightness of a creative relative to its peak (most ads are dark with bright type),
# and an artistic gain: the sim keeps screens at 120 cd/m2 at night so they do not clip
# under the ten-stop night exposure, but a real LED wall is thousands of nits and floods
# the street.  The gain puts the lit ground/facades back at that order of magnitude.
SCREEN_MEAN_POWER = 0.45
SCREEN_SPILL_GAIN = 4.0

NEON_SPILL = MATERIAL_LIGHT + f"const float NEON_GAIN = exp2({NEON_EXPOSURE_STOPS});\n" + f"""
const float SCREEN_MEAN_POWER = {SCREEN_MEAN_POWER};
const float SCREEN_SPILL_GAIN = {SCREEN_SPILL_GAIN};
""" + """
#define MAX_NEON 48
uniform vec3 uNeonPos[MAX_NEON];
uniform vec3 uNeonCol[MAX_NEON];
// LED screens: xy = outward normal (facade screens are vertical, so z is 0), zw = half width and
// half height in metres.  xy = 0 marks an ordinary sign.
uniform vec4 uNeonScr[MAX_NEON];
uniform int  uNumNeon;
// uNeonPos of a screen sits this far in front of its glass (SCREEN_LIGHT_SETBACK, render/lod.py)
const float NEON_SCREEN_SETBACK = 3.0;

bool neonIsScreen(int i) { vec2 n = uNeonScr[i].xy; return dot(n, n) > 0.25; }

// Ordinary signs and shop windows: small omnidirectional sources, unchanged look.
vec3 neonSpill(vec3 P, vec3 N, vec3 V) {
    vec3 acc = vec3(0.0);
    for (int i = 0; i < MAX_NEON; i++) {
        if (i >= uNumNeon) break;
        if (neonIsScreen(i)) continue;
        vec3 d = uNeonPos[i] - P;
        float r2 = dot(d, d);
        if (r2 > 6400.0) continue;
        vec3 L = d * inversesqrt(max(r2, 0.001));
        float diff = max(dot(N, L), 0.0);
        vec3 H = normalize(L + V);
        float spec = pow(max(dot(N, H), 0.0), 32.0);
        float atten = 1.0 / (r2 + 45.0);
        float heightFade = 1.0 - smoothstep(10.0, 55.0, P.z);
        acc += uNeonCol[i] * (diff * 5.0 + spec * 14.0) * atten * heightFade;
    }
    // Sign radiance times a small emitting area, in the same units as sun / lamp spill.
    return acc * nits(SIGN_NITS) * NEON_GAIN;
}

// LED advertising screens as what they are: flat rectangular Lambertian emitters.
// Returns irradiance in the same scene units as sun / lamp spill, so the caller applies
// the surface's own albedo (a wall must not glow white just because a screen is near).
//
//   * One-sided: a point at or behind the glass plane gets nothing.  This is what keeps
//     the host facade, the wall behind it and everything beside the screen from being
//     washed by a point light that used to radiate in every direction.
//   * Near field is bounded: distance is taken to the nearest point on the rectangle and
//     softened by the area (E = L A cos cos / (r^2 + A/pi)), so there is no hot spot
//     just in front of the glass and the limit at the glass is pi * L.
//   * Reaches the ground and the opposite facades by the inverse-square law instead of
//     a height cut-off.
vec3 neonScreenSpill(vec3 P, vec3 N, vec3 V, out vec3 specOut) {
    vec3 acc = vec3(0.0), accSpec = vec3(0.0);
    for (int i = 0; i < MAX_NEON; i++) {
        if (i >= uNumNeon) break;
        vec4 scr = uNeonScr[i];
        if (dot(scr.xy, scr.xy) <= 0.25) continue;
        vec3 nrm = vec3(normalize(scr.xy), 0.0);
        vec3 g = uNeonPos[i] - nrm * NEON_SCREEN_SETBACK;      // centre of the glass
        vec3 rel = P - g;
        float h = dot(rel, nrm);                                // metres in front of the glass
        if (h <= 0.05) continue;
        float rc2 = dot(rel, rel);
        if (rc2 > 22500.0) continue;                            // 150 m
        vec2 ext = max(scr.zw, vec2(0.5));
        vec3 t = vec3(-nrm.y, nrm.x, 0.0);                      // horizontal axis of the glass
        vec3 b = cross(nrm, t);
        vec2 uv = vec2(dot(rel, t), dot(rel, b));
        vec2 off = uv - clamp(uv, -ext, ext);                   // in-plane gap to the rectangle
        float dr2 = h * h + dot(off, off);                      // distance to rectangle, squared
        float dr = sqrt(dr2);
        float area = 4.0 * ext.x * ext.y;
        float cosE = h / dr;                                    // emission angle
        // direction from the receiver to the nearest point on the glass
        vec3 nearest = g + t * clamp(uv.x, -ext.x, ext.x) + b * clamp(uv.y, -ext.y, ext.y);
        vec3 L = (nearest - P) / dr;
        float cosR = max(dot(N, L), 0.0);
        float fade = 1.0 - smoothstep(90.0, 150.0, sqrt(rc2));
        float form = area / (dr2 + area * 0.3183);              // A / (r^2 + A/pi)
        // chroma only: brightness comes from the screen's luminance below
        vec3 c = min(uNeonCol[i] / max(dot(uNeonCol[i], PHOTO_LUMA), 1e-4), vec3(2.5));
        float E = form * cosE * fade;
        acc += c * (E * cosR);
        // broad glint of a big source on glossy glass / wet paving, not a pin-point hot spot
        vec3 H = normalize(L + V);
        accSpec += c * (E * pow(max(dot(N, H), 0.0), 16.0));
    }
    float lum = mix(SCREEN_DAY_NITS, SCREEN_NIGHT_NITS, uNightFactor)
              * SCREEN_MEAN_POWER * SCREEN_SPILL_GAIN;
    specOut = accSpec * nits(lum) * NEON_GAIN * 0.12;
    return acc * nits(lum) * NEON_GAIN;
}
"""

NEON_VS = """
#version 330 core
layout(location=0) in vec3 aPos;
layout(location=1) in vec3 aNormal;
layout(location=2) in vec3 aColor;
layout(location=3) in float aAO;
layout(location=4) in vec3 aStyle;
layout(location=5) in vec2 aUV;
layout(location=6) in float aEmissive;
layout(location=7) in float aPartKind;
uniform mat4 uView, uProj;
uniform vec3 uOffset;
uniform vec2 uScale;
uniform float uGrow;
uniform float uDepthQ;       // 1 / (near * 2^24): one 24-bit depth step per metre^2 of range
out vec3 vWorld;
out vec3 vColor;
out vec3 vStyle;
out vec2 vUV;
out float vPartKind;
out float vLocalZ;
void main() {
    vec3 p = vec3(aPos.xy * uScale, aPos.z * uGrow) + uOffset;
    vWorld = p;
    vColor = aColor;
    vStyle = aStyle;
    vUV = aUV;
    vPartKind = aPartKind;
    vLocalZ = aPos.z;
    // Signs are drawn flush on the facade (and tested against its depth), so they z-fight
    // with it.  Nudge them toward the eye along their own view ray (no on-screen movement)
    // by a few depth quanta, never less than 2 cm.
    vec4 pv = uView * vec4(p, 1.0);
    float zd = max(length(pv.xyz), 1.0);
    float crownRank = aStyle.y == 5.0 ? aAO * 15.0 : 0.0;
    float pull = max(0.02, 4.0 * zd * zd * uDepthQ);
    // LED screens and ticker bands are additive layers standing in front of a frame, the
    // facade and (where OSM overlaps) neighbouring walls.  Under reverse-Z uDepthQ is 0,
    // so the quantum term above vanishes and only 2 cm remained.  Pull them toward the eye
    // by a margin that grows with distance (0.25 %, never under 6 cm): invisible on screen
    // (it is along the view ray), but no wall, frame or neighbour can tie with them.
    if (aStyle.y > 2.5 && aStyle.y < 4.5) pull = max(pull, max(0.06, 0.0025 * zd));
    pv.xyz *= 1.0 - (crownRank * 0.012 + pull) / zd;
    gl_Position = uProj * pv;
}
"""

from .hdr import HDR_CONV, HDR_OUT

NEON_FS = (
"""
#version 330 core
in vec3 vWorld;
in vec3 vColor;
in vec3 vStyle;
in vec2 vUV;
in float vPartKind;
in float vLocalZ;
uniform vec3 uCamPos, uFogColor;
uniform float uFogNear, uFogFar, uNightFactor, uTime, uExposure;
uniform sampler2DArray uBillboards;
uniform int uBillboardCount;
uniform float uBillboardAspect;
uniform float uBillboardOn;
out vec4 FragColor;
"""
    + NEON_SPILL
    + HDR_CONV
    + HDR_OUT
    + """
float hash21(vec2 p) {
    p = fract(p * vec2(123.34, 456.21));
    p += dot(p, p + 45.32);
    return fract(p.x * p.y);
}
vec3 billboardPattern(vec2 uv, vec2 uvDx, vec2 uvDy, float seed, vec3 tint) {
    // Panels keep whatever shape the facade gives them. The 16:9 creative is scaled so it
    // is whole across the panel's short side, then repeats and scrolls along the long side
    // like an LED ticker; each repeat advances to the next creative, so no bars are needed.
    float aspect = max(vStyle.z, 0.3);
    bool wide = aspect >= uBillboardAspect;
    float speed = mix(0.035, 0.085, hash21(vec2(seed * 57.3, 3.1)));   // creatives per second
    float dir = hash21(vec2(seed * 13.7, 9.2)) < 0.5 ? -1.0 : 1.0;
    float n = float(max(uBillboardCount, 1));
    float scroll = mod(uTime, n / speed) * speed;   // one full cycle of creatives; keeps q small
    // q: unwrapped creative coordinates, one unit = one whole creative.
    vec2 q = wide ? vec2((uv.x - 0.5) * aspect / uBillboardAspect + dir * scroll, uv.y)
                  : vec2(uv.x, (uv.y - 0.5) * uBillboardAspect / aspect - scroll);
    vec2 tile = floor(q);
    vec2 f = fract(q);
    float layer = mod(floor(seed * 4096.0) + (wide ? tile.x : tile.y), n);
    // Gradients of the unwrapped coordinate keep mip selection smooth across tile seams.
    // They are the panel's own screen-space footprint (taken by the caller in uniform
    // control flow), so the level is right on every driver: a zero gradient here would
    // pin every screen to mip 0 and alias a creative into a stipple at street distance.
    vec2 qDx = wide ? vec2(uvDx.x * aspect / uBillboardAspect, uvDx.y)
                    : vec2(uvDx.x, uvDx.y * uBillboardAspect / aspect);
    vec2 qDy = wide ? vec2(uvDy.x * aspect / uBillboardAspect, uvDy.y)
                    : vec2(uvDy.x, uvDy.y * uBillboardAspect / aspect);
    vec3 ad = textureGrad(uBillboards, vec3(f, layer), qDx, qDy).rgb;
    // Fine LED scanlines: a band-limited ripple, not a hard square wave.  A square wave
    // carries harmonics far above the line pitch, so on a screen that fills the frame they
    // beat into a visible lattice; a cosine and a fade that starts while a line is still ~2
    // pixels tall keep the weave from ever resolving into stipple.
    float lines = uv.y * 260.0;
    float ripple = 1.0 - smoothstep(0.25, 0.75, (abs(uvDx.y) + abs(uvDy.y)) * 260.0);
    float scan = 1.0 - 0.10 * ripple * (0.5 + 0.5 * cos(lines * 6.2831853));
    return ad * scan * 1.35;
}
vec3 screenPattern(vec2 uv, vec2 uvDx, vec2 uvDy, float seed, float t, vec3 tint, float kind) {
    if (kind < 1.5) {
        // vertical blade: stacked glowing letter blocks
        float rows = 9.0;
        float y = fract(uv.y * rows);
        float band = smoothstep(0.12, 0.20, y) * smoothstep(0.88, 0.78, y);
        float col = step(0.28, fract(uv.x * 3.0 + seed));
        float chase = 0.72 + 0.28 * sin(t * 2.2 + uv.y * 14.0 + seed * 9.0);
        float letters = band * col;
        return tint * (0.35 + 1.9 * letters) * chase;
    }
    if (kind < 3.5) {
        // signage band: continuous luminous strip with ticker
        float tick = step(0.45, fract(uv.x * 0.55 - t * 0.20 + seed));
        float edge = smoothstep(0.0, 0.06, uv.y) * smoothstep(1.0, 0.94, uv.y);
        return tint * (0.55 + 1.7 * tick) * edge;
    }
    if (kind < 4.5) {
        if (uBillboardOn > 0.5 && uBillboardCount > 0)
            return billboardPattern(uv, uvDx, uvDy, seed, tint);
        // Fallback LED billboard: rotating campaigns, bold colour fields, headline bars
        float aspect = max(vStyle.z, 0.3);
        float slot = floor(t / 7.0 + seed * 13.0);
        float fade = smoothstep(0.0, 0.5, fract(t / 7.0 + seed * 13.0)) ;
        float k = hash21(vec2(slot, seed));
        vec2 p = vec2(uv.x * aspect, uv.y);
        vec3 a = tint, b = vec3(1.0) - tint * 0.6;
        vec3 c;
        if (k < 0.34) {
            float d = fract((p.x + p.y * 0.6) * 0.9 - t * 0.05 + seed);
            c = mix(a, b, smoothstep(0.35, 0.65, d)) * (0.8 + 0.5 * step(0.5, fract(p.x * 1.7 - t * 0.2)));
        } else if (k < 0.67) {
            float bars = step(0.5, fract(uv.y * 5.0 + hash21(vec2(slot, 4.0)))) ;
            float len = hash21(vec2(floor(uv.y * 5.0), slot));
            float on = step(uv.x, 0.25 + 0.65 * len) * bars;
            c = mix(a * 0.12, vec3(1.0, 0.97, 0.9), on) + a * 0.25 * (1.0 - uv.y);
        } else {
            vec2 q = vec2(uv.x - 0.5, uv.y - 0.45) * vec2(aspect, 1.0);
            float glow = exp(-dot(q, q) * 3.0);
            float ring = smoothstep(0.03, 0.0, abs(length(q) - 0.45 - 0.05 * sin(t)));
            c = mix(a * 0.2, b, glow) + vec3(1.0) * ring * 0.8;
        }
        vec2 g = fract(uv * vec2(aspect, 1.0) * 16.0);
        float px = 1.0;
        float edge = smoothstep(0.0, 0.02, min(uv.x, 1.0 - uv.x)) * smoothstep(0.0, 0.02, min(uv.y, 1.0 - uv.y));
        return c * px * edge * mix(0.6, 1.0, fade) * 1.5;
    }
    if (kind < 5.5) {
        // multi-tier advertising screen: colour blocks + scrolling captions
        float tier = floor(uv.y * 3.0);
        float seg = floor(uv.x * 4.0 - t * (0.35 + 0.1 * tier));
        float on = step(0.30, hash21(vec2(seg, tier + seed)));
        float scan = 0.82 + 0.18 * sin(uv.y * 260.0 + t * 9.0);
        vec3 c = mix(tint, vec3(1.0) - tint, hash21(vec2(seg * 1.7, tier + seed * 2.0)));
        float stripe = smoothstep(0.02, 0.10, abs(fract(uv.y * 3.0) - 0.5));
        return mix(tint * 0.55, c, on) * scan * stripe * 2.6;
    }
    // crown rib / beacon
    float pulse = 0.72 + 0.28 * sin(t * 1.7 + seed * 4.0);
    float rib = smoothstep(0.55, 1.0, abs(uv.x * 2.0 - 1.0));
    return tint * (0.65 + 1.6 * rib) * pulse;
}
void main() {
    int kind = int(floor(vStyle.y + 0.001));
    float seed = vStyle.x;
    float t = uTime;
    vec3 tint = vColor;
    // Screen-space footprint, measured in uniform control flow: dFdx/dFdy inside the kind
    // branches below are undefined by the spec, and a driver that answers zero would pin
    // every LED screen to the sharpest mip.
    vec2 uvDx = dFdx(vUV);
    vec2 uvDy = dFdy(vUV);
    vec3 col;
    if (kind >= 5) {
        col = tint * (0.85 + 0.45 * sin(t * 1.6 + seed));
        if (kind >= 6) {
            float d = length(vUV - vec2(0.5));
            col = tint * max(0.0, 1.0 - d * 2.0) * 2.2;
        }
    } else {
        col = screenPattern(vUV, uvDx, uvDy, seed, t, tint, vStyle.y);
    }
    float flicker = 0.94 + 0.06 * hash21(vec2(floor(t * 12.0), seed));
    col *= flicker;
    // Architectural LEDs switch on at dusk. Signs wash out naturally against daylight
    // because their nits now share the sun's light scale, rather than a display-space overlay.
    if (kind >= 5) col *= smoothstep(0.08, 0.55, uNightFactor);
    float power = clamp(max(col.r, max(col.g, col.b)), 0.0, 1.0);
    float sourceNits = kind >= 6 ? BEACON_NITS : (kind >= 5 ? CROWN_NITS
                     : (kind >= 4 ? mix(SCREEN_DAY_NITS, SCREEN_NIGHT_NITS, uNightFactor)
                     : (kind == 2 ? SHOP_NITS : SIGN_NITS)));
    float dist = length(uCamPos - vWorld);
    float fog = cityFog(dist, vWorld.z, uFogNear, uFogFar);
    // Fog attenuates emitted light; it must not make an unlit sign glow.
    vec3 radiance = emissionNits(linearColor(col), sourceNits) * power * NEON_GAIN;
    FragColor = vec4(sceneOut(radiance), 1.0 - fog);
}
"""
)


